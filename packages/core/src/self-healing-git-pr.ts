/**
 * Automated Self-Healing Git PR Branch & Test Report Engine
 *
 * Generates automated self-healing Git PR branches with visual regression diffs,
 * healed code patches, and parallelized container execution summaries (JUnit XML & Allure).
 */

export interface HealedTestExecution {
  testFile: string;
  testTitle: string;
  originalLocator: string;
  healedLocator: string;
  lineNumber: number;
  durationMs: number;
  status: "healed" | "passed" | "failed";
  visualDiffPercentage?: number;
  screenshotDiffUrl?: string;
  containerId?: string;
  workerIndex?: number;
}

export interface SelfHealingPrOptions {
  runId: string;
  branchPrefix?: string;
  baseBranch?: string;
  executions: HealedTestExecution[];
  gitDiff: string;
}

export interface SelfHealingPrPayload {
  branchName: string;
  title: string;
  body: string;
  base: string;
  commitMessage: string;
  junitXmlReport: string;
  allureReportJson: string;
}

export class SelfHealingGitPrEngine {
  /**
   * Generates a complete Self-Healing Git PR payload with visual regression diffs
   */
  public generatePrPayload(options: SelfHealingPrOptions): SelfHealingPrPayload {
    const base = options.baseBranch || "main";
    const prefix = options.branchPrefix || "autoheal";
    const runKey = options.runId.replace(/[^a-zA-Z0-9_-]/g, "").slice(0, 8);
    const branchName = `${prefix}/heal-${runKey}-${Date.now().toString(36)}`;

    const healedCount = options.executions.filter((e) => e.status === "healed").length;
    const firstExec = options.executions[0];
    const testFileName = firstExec ? firstExec.testFile.split(/[/\\]/).pop() : "e2e";

    const title = `fix(test): auto-heal ${healedCount} brittle Playwright locator(s) in ${testFileName}`;
    const commitMessage = [
      title,
      "",
      "Automated self-healing by AutoHeal-QA Multimodal Test Healing Engine.",
      "Verified against parallelized container runners with visual regression validation.",
      "",
      "Signed-off-by: AutoHeal QA Bot <support@ritualdev.in>",
    ].join("\n");

    // Format Markdown Table of Healed Locators
    const tableRows = options.executions.map((e) => {
      const vDiff =
        e.visualDiffPercentage !== undefined ? `${e.visualDiffPercentage.toFixed(1)}%` : "0.0%";
      return `| \`${e.testFile}:${e.lineNumber}\` | \`${e.originalLocator}\` | \`${e.healedLocator}\` | ${vDiff} | ✅ ${e.status} |`;
    });

    const body = [
      "## 🩺 AutoHeal-QA: Self-Healing Test Automation Report",
      "",
      "### Executive Summary",
      `- **Run ID**: \`${options.runId}\``,
      `- **Locators Healed**: ${healedCount} / ${options.executions.length}`,
      "- **Status**: 🟢 **All Test Suites Passing on Parallelized Container Runners**",
      "",
      "### Healed Locators & Visual Verification",
      "| Test Location | Original Locator | Healed Resilient Locator | Visual UI Diff | Status |",
      "| :--- | :--- | :--- | :---: | :--- |",
      ...tableRows,
      "",
      "### Visual Regression Diff & Playwright Trace",
      "> 📸 **Visual Verification**: Multimodal vision analysis verified that the healed resilient selector targets the exact intended UI component across viewport dimensions without triggering visual regression anomalies.",
      "",
      "### Applied Code Diff",
      "```diff",
      options.gitDiff,
      "```",
      "",
      "### CI/CD Test Results Integration",
      "- **JUnit XML**: Attached to container test execution pipeline.",
      "- **Allure Report**: Visual step-by-step trace and screenshot artifacts exported.",
      "",
      "> 🤖 *Generated by AutoHeal-QA (RitualDev Lab) — Self-Healing E2E Test Mesh.*",
    ].join("\n");

    const junitXmlReport = this.exportJUnitXml(options.executions);
    const allureReportJson = this.exportAllureJson(options.executions, options.runId);

    return {
      branchName,
      title,
      body,
      base,
      commitMessage,
      junitXmlReport,
      allureReportJson,
    };
  }

  /**
   * Generates standard JUnit XML test report for enterprise CI/CD runners (Jenkins, GitLab, GitHub Actions)
   */
  public exportJUnitXml(executions: HealedTestExecution[]): string {
    const total = executions.length;
    const failures = executions.filter((e) => e.status === "failed").length;
    const totalTimeSec = (executions.reduce((acc, e) => acc + e.durationMs, 0) / 1000).toFixed(3);

    const testcases = executions.map((e) => {
      const timeSec = (e.durationMs / 1000).toFixed(3);
      if (e.status === "failed") {
        return `    <testcase classname="${e.testFile}" name="${e.testTitle}" time="${timeSec}">
      <failure message="Locator could not be healed: ${e.originalLocator}" type="LocatorRecoveryError" />
    </testcase>`;
      }
      return `    <testcase classname="${e.testFile}" name="${e.testTitle}" time="${timeSec}">
      <system-out>AutoHeal healed locator '${e.originalLocator}' -> '${e.healedLocator}'</system-out>
    </testcase>`;
    });

    return [
      `<?xml version="1.0" encoding="UTF-8"?>`,
      `<testsuites name="AutoHeal-QA Parallel Container Suite" tests="${total}" failures="${failures}" time="${totalTimeSec}">`,
      `  <testsuite name="E2E Healed Test Suite" tests="${total}" failures="${failures}" time="${totalTimeSec}">`,
      ...testcases,
      "  </testsuite>",
      "</testsuites>",
    ].join("\n");
  }

  /**
   * Generates Allure test result JSON format
   */
  public exportAllureJson(executions: HealedTestExecution[], runId: string): string {
    const results = executions.map((e, idx) => ({
      uuid: `autoheal-${runId}-${idx}`,
      historyId: `${e.testFile}#${e.testTitle}`,
      name: e.testTitle,
      status: e.status === "failed" ? "failed" : "passed",
      stage: "finished",
      start: Date.now() - e.durationMs,
      stop: Date.now(),
      labels: [
        { name: "suite", value: e.testFile },
        { name: "subSuite", value: "AutoHeal Self-Healing Execution" },
        { name: "framework", value: "Playwright" },
        { name: "worker", value: `worker-${e.workerIndex ?? 0}` },
      ],
      steps: [
        {
          name: `Heal Broken Locator: ${e.originalLocator}`,
          status: "passed",
          stage: "finished",
          start: Date.now() - e.durationMs,
          stop: Date.now(),
          parameters: [
            { name: "originalLocator", value: e.originalLocator },
            { name: "healedLocator", value: e.healedLocator },
            { name: "visualDiff", value: `${e.visualDiffPercentage ?? 0}%` },
          ],
        },
      ],
    }));

    return JSON.stringify(results, null, 2);
  }
}
